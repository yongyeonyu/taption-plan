def chrysler(c):
    a, b = "#D9D3C4", "#B8B1A0"
    c.shadow(50, 58)
    c.box(24, 66, 52, 38, a, b, sw=.22)
    c.box(32, 48, 36, 18, a, b, sw=.22, s=1.6)
