def _nubian(c, x, b, w, h, f, f2, trunc=0, s=1.7):
    t = b - h
    if trunc:
        k = trunc / h
        hw = w / 2 * k
        pt = [(x - w / 2, b), (x - hw, t + trunc), (x + hw - 1, t + trunc + 1), (x + hw, t + trunc), (x + w / 2, b)]
    else:
        pt = [(x - w / 2, b), (x, t), (x + w / 2, b)]
    c.poly(pt, f, s=0)
    c.poly([(x + w * .1, b), pt[1] if not trunc else (x, t + trunc), pt[-2] if trunc else (x, t), (x + w / 2, b)], f2, s=0)
    c.poly(pt, "none", s=s)
    k = int(h // 5)
    e = ""
    for i in range(1, k):
        y = b - h * i / k
        if trunc and y < t + trunc:
            continue
        hw = w / 2 * (1 - i / k)
        e += f"M{n(x - hw)} {n(y)}H{n(x + hw)}"
    c.p(e, s=.42, col="#5F3A24")


