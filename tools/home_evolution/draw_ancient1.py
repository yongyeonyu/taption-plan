def _tier(c, l, r, y0, y1, ins, f, f2, s=1.5):
    c.poly([(l, y0), (l + ins, y1), (r - ins, y1), (r, y0)], f, s=0)
    c.poly([(r - (r - l) * .26, y0), (r - (r - l) * .26 + ins * .3, y1), (r - ins, y1), (r, y0)], f2, s=0)
    c.poly([(l, y0), (l + ins, y1), (r - ins, y1), (r, y0)], "none", s=s)


