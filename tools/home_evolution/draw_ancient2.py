def _ring(cx, rx, y, h, k, sag=3, a=1.2, fill=.62, xmax=999):
    """둥근 벽 정면의 아치 구멍. 양끝으로 갈수록 좁아진다."""
    o = ""
    for i in range(k):
        t0 = -a + 2 * a * i / k
        t1 = t0 + 2 * a / k
        x0, x1 = cx + rx * math.sin(t0), cx + rx * math.sin(t1)
        if x1 > xmax:
            continue
        m, r = (x0 + x1) / 2, (x1 - x0) * fill / 2
        yy = y + sag * math.cos((t0 + t1) / 2)
        o += f"M{n(m - r)} {n(yy)}V{n(yy - h + r)}A{n(r)} {n(r)} 0 0 1 {n(m + r)} {n(yy - h + r)}V{n(yy)}z"
    return o


def _cols(c, x, y, w, h, k, f, f2=None, cw=None, s=1.1, cap=True):
    """기둥 줄을 한 경로로. 주두 띠와 그늘 포함."""
    cw = cw or max(2, w / k * .46)
    gap = (w - cw) / (k - 1) if k > 1 else 0
    xs = [x + gap * i for i in range(k)]
    c.p("".join(f"M{n(q)} {n(y)}h{n(cw)}v{n(h)}h{n(-cw)}z" for q in xs), f, s=s)
    if f2:
        c.p("".join(f"M{n(q + cw * .62)} {n(y + .6)}h{n(cw * .3)}v{n(h - 1.2)}h{n(-cw * .3)}z" for q in xs), f2, s=0)
    if cap:
        c.p("".join(f"M{n(q - .7)} {n(y + .5)}h{n(cw + 1.4)}" for q in xs), s=1)


def _arcade(x, top, w, bot, spans, ah, fill=.7):
    """아래가 뚫린 아치 벽 윤곽. spans는 개수 또는 폭 비율, ah는 높이 또는 목록."""
    sp = [1] * spans if isinstance(spans, int) else spans
    tot, cur, o = sum(sp), x, f"M{n(x)} {n(top)}V{n(bot)}"
    for i, q in enumerate(sp):
        cw = w * q / tot
        m, r = cur + cw / 2, cw * fill / 2
        hh = ah[i] if isinstance(ah, (list, tuple)) else ah
        o += f"H{n(m - r)}V{n(bot - hh + r)}A{n(r)} {n(r)} 0 0 1 {n(m + r)} {n(bot - hh + r)}V{n(bot)}"
        cur += cw
    return o + f"H{n(x + w)}V{n(top)}z"


def _piers(x, w, k, y0, y1, step, fill=.7):
    """아치 사이 기둥의 돌 켜 줄."""
    cw, o = w / k, ""
    pw = cw * (1 - fill)
    for i in range(k + 1):
        cx = x + cw * i
        a, b = max(x, cx - pw / 2), min(x + w, cx + pw / 2)
        yy = y0 + step
        while yy < y1:
            o += f"M{n(a)} {n(yy)}H{n(b)}"
            yy += step
    return o


