def _wall_run(c, pp, th, f):
    """성벽 한 줄기. 윗선을 따라 여장을 세운다."""
    top = pts(pp).replace(",", " ")
    bot = pts([(x, y + th) for x, y in reversed(pp)]).replace(",", " ")
    tooth = ""
    for (x0, y0), (x1, y1) in zip(pp, pp[1:]):
        k = max(1, int(abs(x1 - x0) / 3.4))
        for i in range(k):
            t = i / k
            x, y = x0 + (x1 - x0) * t, y0 + (y1 - y0) * t
            tooth += f"M{n(x + .4)} {n(y)}v-2.4h1.8v{n(2.4 + (y1 - y0) / k * .5)}z"
    c.p(tooth, f, s=.7)
    c.p(f"M{top}L{bot}z", f, s=1.5)
    mid = pts([(x, y + th * .5) for x, y in pp]).replace(",", " ")
    c.p(f"M{mid}", s=.45, col="#7E7562")

