def _kroof(c, cx, y, w, h, f, lines=14, lift=4, top=.6, ridge="#2F3439", line="#3F464C", s=1.8):
    """동아시아 기와지붕: 처마가 들리고 기왓골이 있다. y는 처마."""
    a, b, t = cx - w / 2, cx + w / 2, w * top / 2
    c.p(f"M{n(a)} {n(y - lift)}Q{n(a + w * .07)} {n(y + .3)} {n(a + w * .18)} {n(y + .3)}H{n(b - w * .18)}Q{n(b - w * .07)} {n(y + .3)} {n(b)} {n(y - lift)}Q{n(b - w * .13)} {n(y - h * .4)} {n(cx + t)} {n(y - h)}H{n(cx - t)}Q{n(a + w * .13)} {n(y - h * .4)} {n(a)} {n(y - lift)}z", f, s)
    if lines:
        d_ = ""
        for i in range(lines + 1):
            u = i / lines * 2 - 1
            d_ += f"M{n(cx + u * (w / 2 - w * .14))} {n(y - .6)}L{n(cx + u * t)} {n(y - h + 1)}"
        c.p(d_, s=.45, col=line)
    c.p(f"M{n(cx - t - 1.6)} {n(y - h - 1.6)}Q{n(cx - t)} {n(y - h)} {n(cx - t + 2)} {n(y - h)}H{n(cx + t - 2)}Q{n(cx + t)} {n(y - h)} {n(cx + t + 1.6)} {n(y - h - 1.6)}", s=1.9, col=ridge)


