D = {}
def d(f):
    D[f.__name__] = f
    return f


def _box(c, x, y, w, h, f, f2, sw=.28, s=2):
    """윤곽 한 번만 그리는 그늘 상자."""
    c.r(x, y, w, h, f, s=s)
    c.r(x + w * (1 - sw), y + s / 2, w * sw - s / 2, h - s, f2, s=0)


def _rt(c, cx, y, w, h, f, f2, roof, rh=None, s=1.4):
    """둥근 탑과 원뿔 지붕. 화살창 하나."""
    _box(c, cx - w / 2, y - h, w, h, f, f2, sw=.32, s=s)
    t = y - h
    c.l(cx - .8, t + 4, cx - .8, t + 8, s=.8)
    c.poly([(cx - w / 2 - 1.4, t), (cx, t - (rh or w * 1.3)), (cx + w / 2 + 1.4, t)], roof, s=s)


def _lancet(c, x, y, w, h, f=WIN, s=.8):
    """첨두 아치 창. x는 가운데, y는 바닥."""
    c.p(f"M{n(x - w / 2)} {n(y)}V{n(y - h + w * .8)}L{n(x)} {n(y - h)}L{n(x + w / 2)} {n(y - h + w * .8)}V{n(y)}z", f, s)


def _pin(c, x, y, w, h, f):
    """작은 첨탑."""
    c.poly([(x - w / 2, y), (x, y - h), (x + w / 2, y)], f, s=.9)


