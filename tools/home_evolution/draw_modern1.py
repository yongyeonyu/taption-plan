def _bands(c, x0, x1, t0, t1, b0, b1, ny, nx, win, wall, fill=.55):
    """원근이 있는 벽의 창 띠. 어두운 띠를 벽색 기둥선으로 끊어 창을 만든다."""
    q = ""
    for j in range(ny):
        f, g = (j + .5 - fill / 2) / ny, (j + .5 + fill / 2) / ny
        q += f"M{n(x0)} {n(t0 + (b0 - t0) * f)}L{n(x1)} {n(t1 + (b1 - t1) * f)}V{n(t1 + (b1 - t1) * g)}L{n(x0)} {n(t0 + (b0 - t0) * g)}z"
    c.p(q, win, s=0)
    q = ""
    for i in range(1, nx):
        f = i / nx
        y0, y1 = t0 + (t1 - t0) * f, b0 + (b1 - b0) * f
        q += f"M{n(x0 + (x1 - x0) * f)} {n(y0)}V{n(y1)}"
    c.p(q, s=1, col=wall)


def _ar(c, x, y, w, h, k, f=WIN, fill=.62):
    """아치 k개를 한 경로로."""
    cw, r = w / k, w / k * fill / 2
    q = "".join(f"M{n(x + cw * (i + .5) - r)} {n(y)}V{n(y - h + r)}a{n(r)} {n(r)} 0 0 1 {n(2 * r)} 0V{n(y)}z" for i in range(k))
    c.p(q, f, s=0)


def _ionic(c, x, y, w, h, k, f, f2):
    """이오니아식 주두가 있는 기둥 줄."""
    gap = (w - 2.6) / (k - 1)
    c.columns(x, y + 1.6, w, h - 1.6, k, f, f2, cw=2.6)
    c.p("".join(f"M{n(x + gap * i - .7)} {n(y + 1.2)}a1 1 0 1 1 1 0h2a1 1 0 1 1 1 0" for i in range(k)), f, s=.7)


