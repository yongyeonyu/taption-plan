D = {}


_RECT = re.compile(r'<rect x="([^"]*)" y="([^"]*)" width="([^"]*)" height="([^"]*)"((?: fill="[^"]*")(?: stroke-width="[^"]*")?(?: stroke="none")?)/>$')
_PATH = re.compile(r'<path d="([^"]*)"([^>]*)/>$')


def _compact(parts):
    """사각형을 경로로 바꾸고 이어지는 같은 색의 윤곽 없는 면을 합쳐 용량을 줄인다."""
    out = []
    for part in parts:
        m = _RECT.match(part)
        if m:
            part = f'<path d="M{m[1]} {m[2]}h{m[3]}v{m[4]}h-{m[3]}z"{m[5]}/>'
        m = _PATH.match(part)
        prev = _PATH.match(out[-1]) if out else None
        if m and prev and 'stroke="none"' in m[2] and prev[2] == m[2]:
            out[-1] = f'<path d="{prev[1]}{m[1]}"{m[2]}/>'
        else:
            out.append(part)
    return out


def d(f):
    def draw(c):
        f(c)
        c.parts = _compact(c.parts)
    D[f.__name__] = draw
    return draw


def _box(c, x, y, w, h, f, f2=None, sw=.28, s=2):
    """윤곽 있는 상자와 안쪽 그늘 띠(kit의 box보다 요소가 하나 적다)."""
    c.r(x, y, w, h, f, s=s)
    if f2:
        k = s / 2
        c.r(x + w * (1 - sw), y + k, w * sw - k, h - s, f2, s=0)


def _bullet(c, x, w, top, base, f, f2=None, s=1.4):
    """둥근 끝의 가는 탑(에메랄드 시티)."""
    a, b = x - w / 2, x + w / 2
    c.p(f"M{n(a)} {n(base)}C{n(a)} {n(top + w * 2)} {n(x - w * .2)} {n(top + w * .6)} {n(x)} {n(top)}C{n(x + w * .2)} {n(top + w * .6)} {n(b)} {n(top + w * 2)} {n(b)} {n(base)}z", f, s=s)
    if f2:
        c.p(f"M{n(x + w * .12)} {n(top + w * .9)}C{n(x + w * .3)} {n(top + w * 1.4)} {n(b - .7)} {n(top + w * 2.2)} {n(b - .7)} {n(base - .6)}H{n(x + w * .12)}z", f2, s=0)


def _turret(c, x, w, top, base, rh, wall, shade, roof):
    """원뿔 지붕 탑(신데렐라 성)."""
    _box(c, x - w / 2, top, w, base - top, wall, shade, sw=.3, s=1.4)
    c.p(f"M{n(x - w / 2 - 1.6)} {top}L{n(x)} {top - rh}L{n(x + w / 2 + 1.6)} {top}z", roof, s=1.4)
    c.p(f"M{n(x)} {top - rh}v-3", s=1, col=GOLD2)


def _spiked(c, x, w, top, base, rh, wall, shade, roof):
    """어두운 돌 탑과 가파른 지붕(호그와트)."""
    _box(c, x - w / 2, top, w, base - top, wall, shade, sw=.32, s=1.5)
    c.poly([(x - w / 2 - 1.4, top), (x, top - rh), (x + w / 2 + 1.4, top)], roof, s=1.5)
    c.r(x - w / 2 - .6, top, w + 1.2, 1.6, shade, s=.8)


