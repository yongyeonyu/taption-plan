def _curve(c, x, y, w, sag, s=.6, col=None):
    """둥근 몸통을 따라 처지는 띠."""
    c.p(f"M{n(x)} {n(y)}Q{n(x + w / 2)} {n(y + sag)} {n(x + w)} {n(y)}", s=s, col=col)


def _bulb(c, x, y, r, h, f, s=1.1):
    """작은 양파 지붕."""
    c.onion(x, y, r, h, f) if s == 2 else c.p(
        f"M{n(x - r * .7)} {n(y)}C{n(x - r * 1.5)} {n(y - h * .45)} {n(x - r * .3)} {n(y - h * .7)} {n(x)} {n(y - h)}"
        f"C{n(x + r * .3)} {n(y - h * .7)} {n(x + r * 1.5)} {n(y - h * .45)} {n(x + r * .7)} {n(y)}z", f, s)


def _rects(c, items, f, s=0):
    """사각형 여러 개를 경로 하나로."""
    c.p("".join(f"M{n(x)} {n(y)}h{n(w)}v{n(h)}h{n(-w)}z" for x, y, w, h in items), f, s)


def _slits(c, xs, y, w, h, f=WIN):
    """같은 높이의 위가 둥근 창 여러 개."""
    r = w / 2
    c.p("".join(f"M{n(x - r)} {n(y + h)}V{n(y + r)}a{n(r)} {n(r)} 0 0 1 {n(w)} 0V{n(y + h)}z" for x in xs), f, s=0)


def _lancets(c, xs, y, w, h, f=WIN):
    """같은 높이의 첨두 창 여러 개."""
    r = w / 2
    c.p("".join(f"M{n(x - r)} {n(y + h)}V{n(y + r * 1.5)}L{n(x)} {n(y)}L{n(x + r)} {n(y + r * 1.5)}V{n(y + h)}z" for x in xs), f, s=0)


