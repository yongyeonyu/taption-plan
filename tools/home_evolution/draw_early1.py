def _ad(cx, y, w, h):
    """둥근 아치 경로 조각. y는 바닥."""
    r = w / 2
    return f"M{n(cx - r)} {n(y)}v{n(r - h)}a{n(r)} {n(r)} 0 0 1 {n(w)} 0v{n(h - r)}z"


def _pd(cx, y, w, h):
    """뾰족 아치 경로 조각. y는 바닥."""
    r = w / 2
    return f"M{n(cx - r)} {n(y)}v{n(-h * .55)}q0 {n(-h * .3)} {n(r)} {n(-h * .45)}q{n(r)} {n(h * .15)} {n(r)} {n(h * .45)}v{n(h * .55)}z"


def _rd(x, y, w, h):
    return f"M{n(x)} {n(y)}h{n(w)}v{n(h)}h{n(-w)}z"


def _col(c, x, y, w, h, k, f=MARBLE, f2=MARBLE2, cw=None):
    """기둥 줄을 경로 둘로 묶어 그린다."""
    cw = cw or max(2.4, w / k * .46)
    gap = (w - cw) / (k - 1) if k > 1 else 0
    c.p("".join(_rd(x + gap * i, y, cw, h) for i in range(k)), f, s=1.2)
    if f2:
        c.p("".join(_rd(x + gap * i + cw * .62, y + .6, cw * .3, h - 1.2) for i in range(k)), f2, s=0)


def _tips(xs, y, h):
    """난간 위 조각·첨두 같은 짧은 세로선."""
    return "".join(f"M{n(x)} {n(y)}v{n(-h)}" for x in xs)


def _chhatri(c, x, y, w, h, wall, top, s=1):
    """기둥 위 작은 돔 정자. y는 바닥."""
    c.r(x - w / 2, y - h, w, h, wall, s=s)
    c.r(x - w / 2 - .8, y - h - 1, w + 1.6, 1.2, wall, s=.7)
    c.onion(x, y - h - 1, w * .42, w, top)


