def _hanok(c, cx, y, w, h, f, roof, rh, frames=4, wall="#F3EEE1"):
    """맞배·팔작 민가형 당집. y는 바닥."""
    x = cx - w / 2
    c.r(x, y - h, w, h, wall, s=1.1)
    c.p("".join(f"M{n(x + w * i / frames)} {n(y - h)}v{n(h)}" for i in range(frames + 1)) + f"M{n(x)} {n(y - h * .35)}h{n(w)}", s=.8, col=f)
    c.eave(cx, y - h + .6, w * 1.34, rh, roof)


