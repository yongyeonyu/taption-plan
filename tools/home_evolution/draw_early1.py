def _mill(c, x, base, h, w, k, ang, body, cap):
    """네덜란드 초가 풍차. 몸통 팔각, 꼭대기 모자, 네 날개."""
    t = base - h
    c.p(f"M{n(x - w / 2)} {base}L{n(x - w * .28)} {n(t)}H{n(x + w * .28)}L{n(x + w / 2)} {base}z", body, s=1.7 if k > .7 else 1.2)
    c.p(f"M{n(x - w * .28)} {n(t)}Q{x} {n(t - w * .5)} {n(x + w * .28)} {n(t)}z", cap, s=1.4 if k > .7 else 1)
    hx, hy = x, t - w * .05
    blade, rung, arm = "", "", ""
    for i in range(4):
        a = ang + i * math.pi / 2
        ca, sa = math.cos(a), math.sin(a)
        ex, ey = hx + 30 * k * ca, hy + 30 * k * sa
        bx, by = hx + 8 * k * ca, hy + 8 * k * sa
        nx, ny = -sa * 5 * k, ca * 5 * k
        blade += f"M{n(bx)} {n(by)}L{n(ex)} {n(ey)}l{n(nx)} {n(ny)}L{n(bx + nx)} {n(by + ny)}z"
        rung += "".join(f"M{n(bx + (ex - bx) * f)} {n(by + (ey - by) * f)}l{n(nx)} {n(ny)}" for f in (.3, .65))
        arm += f"M{n(hx)} {n(hy)}L{n(ex)} {n(ey)}"
    c.p(blade, "#F4EFE1", s=.9)
    c.p(rung, s=.5)
    c.p(arm, s=1.5 if k > .7 else 1)
    c.c(hx, hy, 2.2 * k + .6, "#3F3E44", s=.7)


